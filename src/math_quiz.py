# Модуль: Навчальна вікторина з інформатики для 8-9 класів
# Дисципліна: Командна розробка програмних проєктів

def calculate_score(correct, total):
    """Обчислення відсотка правильних відповідей"""
    if total == 0:
        return 0
    return (correct / total) * 100

def start_quiz():
    """Запуск навчального опитування"""
    print("=" * 45)
    print("Вітаємо у вікторині освітнього проєкту PythonStart!")
    print("=" * 45)
    score = 0
    total_questions = 2

    # Питання 1
    print("\nПитання 1: Чому дорівнює результат виразу 10 + 2 * 3 у мові Python?")
    ans1 = input("Введіть відповідь: ").strip()
    if ans1 == "16":
        print("Правильно! Пріоритет множення вищий за додавання.")
        score += 1
    else:
        print("Помилка. Спочатку виконується множення: 2 * 3 = 6, потім 10 + 6 = 16.")

    # Питання 2
    print("\nПитання 2: Який результат дасть операція цілочисельного ділення 15 // 4?")
    ans2 = input("Введіть відповідь: ").strip()
    if ans2 == "3":
        print("Правильно! 15 вміщує 4 тричі з остачею 3.")
        score += 1
    else:
        print("Помилка. Оператор // відкидає дробову частину числа.")

    # Підсумок
    percent = calculate_score(score, total_questions)
    print("-" * 45)
    print(f"Підсумок: {score} із {total_questions} правильних відповідей ({percent}%).")

if __name__ == "__main__":
    start_quiz()
