"""
Модуль з інтерактивними завданнями та перевіркою відповідей.
"""

TASKS = [
    {
        "question": "Яким оператором виводять текст на екран у Python?",
        "answer": "print",
        "hint": "Це вбудована функція з 5 літер, яку ти вже бачив у прикладах.",
    },
    {
        "question": "Яке ключове слово починає умовний оператор у Python?",
        "answer": "if",
        "hint": "Два символи, англійське слово «якщо».",
    },
    {
        "question": "Яку функцію використовують для зчитування введення з клавіатури?",
        "answer": "input",
        "hint": "Вона повертає рядок із введеними даними.",
    },
    {
        "question": "Як називається тип даних для цілих чисел у Python?",
        "answer": "int",
        "hint": "Скорочення від англійського слова 'integer'.",
    },
    {
        "question": "Яке ключове слово використовується для створення циклу з лічильником?",
        "answer": "for",
        "hint": "Три літери, англійське прийменникове слово.",
    },
]


def run_tasks():
    print("\n── Практичні завдання ─────────────────────────")
    correct = 0

    for i, task in enumerate(TASKS, start=1):
        print(f"\nЗавдання {i}/{len(TASKS)}: {task['question']}")
        answer = input("Ваша відповідь: ").strip().lower()

        if answer == task["answer"].lower():
            print("✅ Правильно!")
            correct += 1
        else:
            print(f"❌ Неправильно. Підказка: {task['hint']}")
            print(f"   Правильна відповідь: {task['answer']}")

    print(f"\n── Результат: {correct}/{len(TASKS)} правильних відповідей ──")
    pct = correct / len(TASKS) * 100
    if pct == 100:
        print("🏆 Чудово! Ви впоралися з усіма завданнями!")
    elif pct >= 60:
        print("👍 Непоганий результат! Продовжуйте практикуватися.")
    else:
        print("📚 Поверніться до теоретичних карток і спробуйте знову.")
    print()
